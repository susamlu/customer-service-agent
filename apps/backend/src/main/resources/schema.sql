-- 转人工工单（architecture.md §6）。全部 IF NOT EXISTS，重复执行幂等。
CREATE TABLE IF NOT EXISTS ticket (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(64)  NOT NULL,
    user_id    VARCHAR(64),
    status     VARCHAR(16)  NOT NULL,
    query      VARCHAR(512) NOT NULL,
    context    VARCHAR(4000),
    created_at BIGINT       NOT NULL,
    updated_at BIGINT       NOT NULL
);

-- 列表按状态过滤、建单前查同会话未结束工单，都走这个索引。
CREATE INDEX IF NOT EXISTS idx_ticket_status ON ticket (status, id);
CREATE INDEX IF NOT EXISTS idx_ticket_session ON ticket (session_id, id);
